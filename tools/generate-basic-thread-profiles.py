"""Generate original language-neutral metric and trapezoidal profile diagrams."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'config/lib/03-ENGINEERING-TABLES/03-THREADS'


def profile(angle):
    pitch = 260
    half = math.radians(angle / 2)
    if angle == 60:
        triangle = pitch / (2 * math.tan(half))
        depth = 5 * triangle / 8
        top_half, bottom_half = pitch / 16, pitch / 8
        formula = 'H = √3P/2 · h = 5H/8'
    else:
        depth = pitch / 2
        top_half = bottom_half = (pitch - 2 * depth * math.tan(half)) / 4
        formula = 'h = P/2 · Ph = nP'
    top = 94
    bottom = top + depth
    points = []
    for i in range(3):
        center = 160 + i * pitch
        points += [(center-top_half, top), (center+top_half, top)]
        if i < 2:
            valley = center + pitch / 2
            points += [(valley-bottom_half, bottom), (valley+bottom_half, bottom)]
    vertices = ' '.join(f'{x:.5f},{y:.5f}' for x, y in points)
    vertex_y = bottom + bottom_half / math.tan(half)
    vx = 160 + pitch / 2
    ar = 67
    dx, dy = ar * math.sin(half), ar * math.cos(half)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 390" role="img">
<title>Original ZIMA {angle}° basic thread profile</title>
<metadata>Copyright 2026 Vladimir Zima / ZIMA Engineering. GPL-3.0-or-later. Generated by tools/generate-basic-thread-profiles.py.</metadata>
<defs><marker id="a" viewBox="0 0 10 10" refX="5" refY="5" markerWidth="5" markerHeight="5" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 Z" fill="#202a35"/></marker></defs>
<rect width="900" height="390" fill="white"/>
<g fill="none" stroke="#202a35" stroke-width="1.5">
<path d="M160 22 V84 M420 22 V84 M720 {top} H827 M720 {bottom:.5f} H827"/>
<path d="M160 36 H420 M810 {top} V{bottom:.5f}" marker-start="url(#a)" marker-end="url(#a)"/>
<path d="M100 {top} H730 M100 {bottom:.5f} H730" stroke-dasharray="6 5" stroke="#81909b"/>
<path d="M{vx-dx:.5f} {vertex_y-dy:.5f} L{vx:.5f} {vertex_y:.5f} L{vx+dx:.5f} {vertex_y-dy:.5f}" stroke-dasharray="4 4" stroke="#81909b"/>
<path d="M{vx-dx:.5f} {vertex_y-dy:.5f} A{ar} {ar} 0 0 1 {vx+dx:.5f} {vertex_y-dy:.5f}" marker-start="url(#a)" marker-end="url(#a)"/>
<polyline points="{vertices}" stroke-width="3"/>
</g>
<g fill="#202a35" font-family="Arial,sans-serif" text-anchor="middle" font-size="23">
<text x="290" y="24">P</text><text x="{vx}" y="{vertex_y-dy-12:.5f}">{angle}°</text>
<text x="836" y="{(top+bottom)/2+6:.5f}">h</text><text x="450" y="366">{formula}</text>
</g></svg>
'''


if __name__ == '__main__':
    for folder, name, angle in [('02-METRIC', 'metric-profile.svg', 60), ('06-TRAPEZOID', 'trapezoidal-profile.svg', 30)]:
        target = ROOT / folder / '0000-index' / name
        target.write_text(profile(angle), encoding='utf-8', newline='\n')
        print(target.relative_to(ROOT))
