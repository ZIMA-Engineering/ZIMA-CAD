"""Create ZIMA's original Whitworth schematic from analytic profile geometry."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'config/lib/03-ENGINEERING-TABLES/03-THREADS/04-WHITWORTH/0000-index/whitworth-profile.svg'


def geometry(pitch):
    angle = math.radians(27.5)
    height = pitch / (2 * math.tan(angle))
    radius = height * math.sin(angle) / (6 * (1 - math.sin(angle)))
    return height, 2 * height / 3, radius


def drawing():
    pitch = 300
    angle = math.radians(27.5)
    height, depth, radius = geometry(pitch)
    apex_y = 110 - height / 6
    tangent_x = radius * math.cos(angle)
    tangent_y = radius * math.cos(angle)**2 / math.sin(angle)
    path = []
    # Alternating analytically tangent circular crests and roots, not a tracing.
    for i in range(3):
        x = 170 + i * pitch
        left = (x - tangent_x, apex_y + tangent_y)
        right = (x + tangent_x, apex_y + tangent_y)
        path.append(('M' if i == 0 else 'L') + f'{left[0]:.4f} {left[1]:.4f}')
        path.append(f'A{radius:.4f} {radius:.4f} 0 0 1 {right[0]:.4f} {right[1]:.4f}')
        if i < 2:
            valley = x + pitch / 2
            path.append(f'L{valley-tangent_x:.4f} {apex_y+height-tangent_y:.4f}')
            path.append(f'A{radius:.4f} {radius:.4f} 0 0 0 {valley+tangent_x:.4f} {apex_y+height-tangent_y:.4f}')
    valley = 320
    vertex_y = apex_y + height
    arc = 78
    ax, ay = arc * math.sin(angle), arc * math.cos(angle)
    bottom = 110 + depth
    # The external radius leader lies on a true radius of the first root.
    # Anchor the marker by its tip, exactly on the circular profile.
    center = (valley, bottom - radius)
    direction = (-math.sqrt(.5), math.sqrt(.5))
    contact = tuple(c + radius * d for c, d in zip(center, direction))
    tail = tuple(c + (radius + 80) * d for c, d in zip(center, direction))
    label = (tail[0] + 19, tail[1] - 26)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 460" role="img">
<title>Whitworth 55° profile — original ZIMA Engineering schematic</title>
<desc>Analytically constructed rounded crests and roots. Pitch P, depth h and fillet radius R are dimensioned. No third-party drawing is embedded.</desc>
<metadata>Copyright 2026 Vladimir Zima / ZIMA Engineering. GPL-3.0-or-later. Generated by tools/generate-whitworth-profile.py.</metadata>
<defs><marker id="arrow" viewBox="0 0 10 10" refX="5" refY="5" markerWidth="5" markerHeight="5" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 Z" fill="#202a35"/></marker><marker id="radius-arrow" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="5" markerHeight="5" orient="auto"><path d="M0 0 L10 5 L0 10 Z" fill="#202a35"/></marker></defs>
<rect width="1000" height="460" fill="white"/>
<g fill="none" stroke="#202a35" stroke-width="1.5">
<path d="M170 35 V100 M470 35 V100 M850 110 H925 M850 {bottom:.4f} H925"/>
<path d="M110 110 H850 M110 {bottom:.4f} H850" stroke-dasharray="6 5" stroke="#81909b"/>
<path d="M170 50 H470 M910 110 V{bottom:.4f}" marker-start="url(#arrow)" marker-end="url(#arrow)"/>
<path d="M{valley-ax:.4f} {vertex_y-ay:.4f} L{valley:.4f} {vertex_y:.4f} L{valley+ax:.4f} {vertex_y-ay:.4f}" stroke-dasharray="4 4" stroke="#81909b"/>
<path d="M{valley-ax:.4f} {vertex_y-ay:.4f} A78 78 0 0 1 {valley+ax:.4f} {vertex_y-ay:.4f}" marker-start="url(#arrow)" marker-end="url(#arrow)"/>
<path id="radius-leader" d="M{tail[0]:.4f} {tail[1]:.4f} L{contact[0]:.4f} {contact[1]:.4f}" marker-end="url(#radius-arrow)"/>
<path d="{' '.join(path)}" stroke-width="3"/>
</g>
<g fill="#202a35" font-family="Arial,sans-serif" text-anchor="middle" font-size="24">
<text x="320" y="36">P</text><text x="320" y="254">55°</text>
<text x="934" y="214">h</text><text x="{label[0]:.4f}" y="{label[1]:.4f}" transform="rotate(-45 {label[0]:.4f} {label[1]:.4f})">R</text>
<text x="500" y="396" font-size="21">H = P / (2 tan 27.5°) · h = 2H/3</text>
<text x="500" y="429" font-size="21">h ≈ 0.640327P · R ≈ 0.137329P</text>
</g></svg>
'''


if __name__ == '__main__':
    TARGET.write_text(drawing(), encoding='utf-8', newline='\n')
    print(TARGET.relative_to(ROOT))
